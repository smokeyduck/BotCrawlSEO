"""
Report generation module for SEO Analysis Tool
"""

import os
from datetime import datetime
import config
import utils

class ReportGenerator:
    """
    Generate comprehensive SEO analysis reports in text format
    """
    
    def __init__(self):
        self.logger = utils.setup_logging()
    
    def generate_report(self, url, keyword_analysis, link_analysis, seo_analysis, parsed_data):
        """
        Generate comprehensive SEO report
        
        Args:
            url (str): Analyzed URL
            keyword_analysis (dict): Keyword analysis results
            link_analysis (dict): Link analysis results
            seo_analysis (dict): SEO metrics analysis results
            parsed_data (dict): Raw parsed data
            
        Returns:
            str: Path to generated report file
        """
        try:
            # Create output directory
            utils.create_output_directory()
            
            # Generate report content
            report_content = self._build_report_content(
                url, keyword_analysis, link_analysis, seo_analysis, parsed_data
            )
            
            # Generate filename and save report
            domain = utils.get_domain_from_url(url)
            filename = utils.generate_report_filename(domain)
            filepath = os.path.join(config.OUTPUT_DIR, filename)
            
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(report_content)
            
            self.logger.info(f"Report generated: {filepath}")
            return filepath
            
        except Exception as e:
            self.logger.error(f"Error generating report: {e}")
            return None
    
    def _build_report_content(self, url, keyword_analysis, link_analysis, seo_analysis, parsed_data):
        """Build the complete report content"""
        report_sections = []
        
        # Header
        report_sections.append(self._generate_header(url))
        
        # Executive Summary
        report_sections.append(self._generate_executive_summary(keyword_analysis, link_analysis, seo_analysis))
        
        # Keyword Analysis Section
        report_sections.append(self._generate_keyword_section(keyword_analysis))
        
        # Link Analysis Section
        report_sections.append(self._generate_link_section(link_analysis))
        
        # SEO Metrics Section
        report_sections.append(self._generate_seo_section(seo_analysis))
        
        # Technical Details Section
        report_sections.append(self._generate_technical_section(parsed_data))
        
        # Recommendations Section
        report_sections.append(self._generate_recommendations_section(seo_analysis))
        
        # Footer
        report_sections.append(self._generate_footer())
        
        return '\n\n'.join(report_sections)
    
    def _generate_header(self, url):
        """Generate report header"""
        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        domain = utils.get_domain_from_url(url)
        
        return f"""
{'='*80}
                        SEO ANALYSIS REPORT
{'='*80}

Website: {url}
Domain: {domain}
Analysis Date: {timestamp}
Generated by: Advanced SEO Analysis Tool

{'='*80}
        """.strip()
    
    def _generate_executive_summary(self, keyword_analysis, link_analysis, seo_analysis):
        """Generate executive summary"""
        seo_score = seo_analysis.get('seo_score', 0)
        total_keywords = len(keyword_analysis.get('primary_keywords', []))
        total_links = link_analysis.get('total_links', 0)
        
        summary = f"""
EXECUTIVE SUMMARY
{'-'*50}

Overall SEO Score: {seo_score}/100

Key Metrics:
• Primary Keywords Identified: {total_keywords}
• Total Links Found: {total_links}
• Internal Links: {link_analysis.get('link_statistics', {}).get('internal_count', 0)}
• External Links: {link_analysis.get('link_statistics', {}).get('external_count', 0)}

Content Statistics:
• Word Count: {keyword_analysis.get('content_stats', {}).get('word_count', 0)}
• Reading Level: {keyword_analysis.get('content_stats', {}).get('reading_level', 'N/A')}
        """
        
        return summary.strip()
    
    def _generate_keyword_section(self, keyword_analysis):
        """Generate keyword analysis section"""
        primary_keywords = keyword_analysis.get('primary_keywords', [])
        secondary_keywords = keyword_analysis.get('secondary_keywords', [])
        
        section = f"""
KEYWORD ANALYSIS
{'-'*50}

PRIMARY KEYWORDS ({len(primary_keywords)} found):
{', '.join(primary_keywords[:20]) if primary_keywords else 'None identified'}

SECONDARY KEYWORDS ({len(secondary_keywords)} found):
{', '.join(secondary_keywords[:30]) if secondary_keywords else 'None identified'}

KEYWORD DENSITY (Top 10):"""
        
        keyword_density = keyword_analysis.get('keyword_density', {})
        if keyword_density:
            for keyword, density in list(keyword_density.items())[:10]:
                section += f"\n• {keyword}: {density}%"
        else:
            section += "\nNo keyword density data available"
        
        # TF-IDF Keywords
        tfidf_keywords = keyword_analysis.get('tfidf_keywords', {})
        if tfidf_keywords:
            section += f"\n\nTF-IDF ANALYSIS (Top 10):"
            for keyword, score in list(tfidf_keywords.items())[:10]:
                section += f"\n• {keyword}: {score:.4f}"
        
        # N-gram Analysis
        ngram_analysis = keyword_analysis.get('ngram_analysis', {})
        if ngram_analysis.get('2_grams'):
            section += f"\n\nCOMMON PHRASES (2-grams):"
            for phrase, count in list(ngram_analysis['2_grams'].items())[:10]:
                section += f"\n• {phrase}: {count}"
        
        return section
    
    def _generate_link_section(self, link_analysis):
        """Generate link analysis section"""
        stats = link_analysis.get('link_statistics', {})
        
        section = f"""
LINK ANALYSIS
{'-'*50}

LINK STATISTICS:
• Total Valid Links: {stats.get('total_valid_links', 0)}
• Internal Links: {stats.get('internal_count', 0)} ({stats.get('internal_percentage', 0)}%)
• External Links: {stats.get('external_count', 0)} ({stats.get('external_percentage', 0)}%)
• Invalid Links: {stats.get('invalid_count', 0)}
• NoFollow Links: {stats.get('nofollow_count', 0)}
• DoFollow Links: {stats.get('dofollow_count', 0)}

EXTERNAL DOMAINS (Top 10):"""
        
        domain_analysis = link_analysis.get('domain_analysis', {})
        top_domains = domain_analysis.get('top_domains', {})
        if top_domains:
            for domain, count in list(top_domains.items())[:10]:
                section += f"\n• {domain}: {count} links"
        else:
            section += "\nNo external domains found"
        
        # Anchor Text Analysis
        anchor_analysis = link_analysis.get('anchor_text_analysis', {})
        external_anchors = anchor_analysis.get('external_anchors', {})
        if external_anchors:
            section += f"\n\nCOMMON EXTERNAL ANCHOR TEXTS (Top 10):"
            for anchor, count in list(external_anchors.items())[:10]:
                section += f"\n• \"{anchor}\": {count}"
        
        return section
    
    def _generate_seo_section(self, seo_analysis):
        """Generate SEO metrics section"""
        section = f"""
SEO METRICS ANALYSIS
{'-'*50}

OVERALL SEO SCORE: {seo_analysis.get('seo_score', 0)}/100

TITLE ANALYSIS:"""
        
        title_analysis = seo_analysis.get('title_analysis', {})
        if title_analysis:
            section += f"""
• Title: "{title_analysis.get('title', 'N/A')}"
• Length: {title_analysis.get('length', 0)} characters
• Score: {title_analysis.get('score', 0)}/100"""
            
            title_issues = title_analysis.get('issues', [])
            if title_issues:
                section += f"\n• Issues: {', '.join(title_issues)}"
        
        section += f"\n\nMETA DESCRIPTION ANALYSIS:"
        meta_analysis = seo_analysis.get('meta_description_analysis', {})
        if meta_analysis:
            section += f"""
• Description: "{meta_analysis.get('description', 'N/A')[:100]}..."
• Length: {meta_analysis.get('length', 0)} characters
• Score: {meta_analysis.get('score', 0)}/100"""
            
            meta_issues = meta_analysis.get('issues', [])
            if meta_issues:
                section += f"\n• Issues: {', '.join(meta_issues)}"
        
        section += f"\n\nHEADING STRUCTURE:"
        heading_structure = seo_analysis.get('heading_structure', {})
        if heading_structure:
            heading_counts = heading_structure.get('heading_counts', {})
            section += f"""
• Total Headings: {heading_structure.get('total_headings', 0)}
• H1: {heading_counts.get('h1', 0)}, H2: {heading_counts.get('h2', 0)}, H3: {heading_counts.get('h3', 0)}
• Score: {heading_structure.get('score', 0)}/100"""
            
            structure_issues = heading_structure.get('structure_issues', [])
            if structure_issues:
                section += f"\n• Issues: {', '.join(structure_issues)}"
        
        section += f"\n\nIMAGE SEO:"
        image_seo = seo_analysis.get('image_seo', {})
        if image_seo:
            section += f"""
• Total Images: {image_seo.get('total_images', 0)}
• Images with Alt Text: {image_seo.get('images_with_alt', 0)}
• Images without Alt Text: {image_seo.get('images_without_alt', 0)}
• Score: {image_seo.get('score', 0)}/100"""
        
        return section
    
    def _generate_technical_section(self, parsed_data):
        """Generate technical details section"""
        section = f"""
TECHNICAL DETAILS
{'-'*50}

PAGE INFORMATION:
• Title: {parsed_data.get('title', 'N/A')}
• Meta Description: {parsed_data.get('meta_description', 'N/A')[:100]}...
• Meta Keywords: {parsed_data.get('meta_keywords', 'N/A')}

CONTENT STRUCTURE:
• Total Images: {len(parsed_data.get('images', []))}
• Total Links: {len(parsed_data.get('links', []))}

META TAGS:"""
        
        meta_tags = parsed_data.get('meta_tags', {})
        important_meta = ['viewport', 'charset', 'robots', 'author']
        for tag in important_meta:
            if tag in meta_tags:
                section += f"\n• {tag}: {meta_tags[tag]}"
        
        return section
    
    def _generate_recommendations_section(self, seo_analysis):
        """Generate recommendations section"""
        recommendations = seo_analysis.get('recommendations', [])
        
        section = f"""
RECOMMENDATIONS
{'-'*50}

Based on the analysis, here are the key recommendations for improving SEO:
"""
        
        if recommendations:
            for i, recommendation in enumerate(recommendations, 1):
                section += f"\n{i}. {recommendation}"
        else:
            section += "\nNo specific recommendations identified. The website appears to follow SEO best practices."
        
        return section
    
    def _generate_footer(self):
        """Generate report footer"""
        return f"""
{'='*80}
Report generated by Advanced SEO Analysis Tool
Analysis completed at: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

For questions or support, please refer to the tool documentation.
{'='*80}
        """.strip()
